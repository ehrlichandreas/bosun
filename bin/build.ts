#!/usr/bin/env node
/**
 * Generate dist/*.mjs from bin/*.ts, so that any Node can run bosun.
 *
 *   node bin/build.ts            write dist/
 *   node bin/build.ts --check    exit 1 if dist/ is behind the source
 *
 * E24 forbade a build step, and its reason was that a build step would be an
 * install for every user rather than only for the author. Running the .ts
 * directly turned out to satisfy the letter and break the reason: it requires
 * a Node built with the type stripper, and the first person to install bosun
 * elsewhere found both of his Node binaries without it and had to put a third
 * one at the front of his PATH - a machine-wide change to keep a decision log.
 * Shipping the stripped output puts the build where E24 wanted it, on this
 * side, and leaves the user with nothing to install.
 *
 * The stripping is done by Node itself, so this adds no dependency here
 * either. Types are replaced by spaces rather than removed, so every line and
 * column in dist matches its source and a stack trace still points at the
 * right place. The shebang is replaced by the generated marker for the same
 * reason: it keeps the line count identical.
 */

import {
  readdirSync,
  readFileSync,
  writeFileSync,
  mkdirSync,
  rmSync,
  existsSync,
} from "node:fs";
import { join } from "node:path";
import { stripTypeScriptTypes } from "node:module";
import { SCRIPT_ROOT, isDirectRun, unknownFlag } from "./paths.ts";

const SOURCE = join(SCRIPT_ROOT, "bin");
const DIST = join(SCRIPT_ROOT, "dist");

export const MARKER =
  "// generated by bin/build.ts - do not edit, edit the .ts source";

/** One source file, stripped of its types and pointed at its siblings. */
export function compile(source: string): string {
  const stripped = stripTypeScriptTypes(source, { mode: "strip" });
  return stripped
    // The .ts extension on a relative import is the right convention for type
    // stripping and wrong for the output, which sits beside .mjs siblings.
    .replace(/(from\s+["']\.\/[^"']+)\.ts(["'])/g, "$1.mjs$2")
    // The shebang goes and the marker takes its line: dist is run as an
    // argument to node, never executed directly, and the line count has to
    // stay equal or a stack trace stops pointing at the right source line.
    .replace(/^#![^\n]*/, MARKER);
}

function sources(): string[] {
  return readdirSync(SOURCE)
    .filter((name) => name.endsWith(".ts"))
    .sort();
}

export function main(argv: string[]): number {
  const unknown = unknownFlag(argv, ["--check"]);
  if (unknown) {
    console.error(`refused: unknown flag ${unknown}`);
    return 1;
  }
  const check = argv.includes("--check");
  const names = sources();
  if (names.length === 0) {
    console.error(`no bin/*.ts found in ${SOURCE}`);
    return 1;
  }

  const behind: string[] = [];
  for (const name of names) {
    const target = join(DIST, name.replace(/\.ts$/, ".mjs"));
    const wanted = compile(readFileSync(join(SOURCE, name), "utf8"));
    const held = existsSync(target) ? readFileSync(target, "utf8") : null;
    if (held === wanted) continue;
    behind.push(name.replace(/\.ts$/, ".mjs"));
    if (!check) {
      mkdirSync(DIST, { recursive: true });
      writeFileSync(target, wanted, "utf8");
    }
  }

  // A file in dist with no source behind it is the same leftover E73 removed
  // from the rendered layer, and worse: somebody's settings.json may still
  // name it, so it would go on being run.
  const wantedNames = new Set(names.map((n) => n.replace(/\.ts$/, ".mjs")));
  const stale = existsSync(DIST)
    ? readdirSync(DIST).filter(
        (name) => name.endsWith(".mjs") && !wantedNames.has(name),
      )
    : [];
  for (const name of stale) {
    console.log(check ? "  no source behind it:" : "  removed:", name);
    if (!check) rmSync(join(DIST, name));
  }

  if (check) {
    for (const name of behind) console.log("  behind the source:", name);
    console.log(
      `${names.length} sources, ${behind.length + stale.length} out of date`,
    );
    return behind.length + stale.length ? 1 : 0;
  }

  console.log(`${names.length} sources, ${behind.length} file(s) written`);
  return 0;
}

if (isDirectRun(import.meta.url)) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    console.error("refused:", (error as Error).message);
    process.exitCode = 1;
  }
}
