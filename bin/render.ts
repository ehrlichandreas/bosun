#!/usr/bin/env node
/**
 * Generate the readable layer from decisions/*.json.
 *
 * Writes one Markdown file per decision plus DECISIONS.md as an index. The
 * index is what a reader loads to browse, so it stays one line per decision no
 * matter how long the log gets.
 *
 *   node bin/render.ts            write the files
 *   node bin/render.ts --check    exit 1 if anything on disk differs
 *
 * Node 22.6+ runs this without a build step. Only node: builtins are used, so
 * there is no package.json and nothing to install.
 */

import {
  readdirSync,
  readFileSync,
  writeFileSync,
  existsSync,
  rmSync,
} from "node:fs";
import { join, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { LATEST, missingFields, validate } from "./schema.ts";
import {
  SCRIPT_ROOT,
  logRoot,
  takeLog,
  unknownFlag,
  noLogRoot,
  decisionsDir,
  readEntryFile,
} from "./paths.ts";
import { isDirectRun } from "./paths.ts";

export type Rejected = { option: string; because: string };

export type Entry = {
  schema: number;
  id: string;
  alias: string | null;
  date: string;
  origin: string;
  author_role: string;
  statement: string;
  quote: { text: string; lang: string } | null;
  trigger: string | null;
  decision: string | null;
  why: string | null;
  rejected: Rejected[];
  reason_type: string | null;
  implementation: string | null;
  consequence: string | null;
  falsifier: string | null;
  supersedes: { id: string; extent: "whole" | "part"; detail: string | null }[];
  note: string | null;
  provenance: string | null;
};

export type Loaded = Entry & { stem: string };

export const INDEX_MARKER =
  "<!-- generated by bin/render.ts - do not edit, edit decisions/*.json -->";

/** Every file this script generates starts with this, and only those do. */
export const GENERATED_PREFIX = "<!-- generated by bin/render.ts";

/**
 * Field values are data, never structure. Unescaped, a value could open a
 * heading, fake the generated marker, or add a table row - forging an entry
 * inside a real generated file that agents read back as memory. Escaping at
 * the interpolation site rather than refusing on save keeps every value
 * sayable; backslash escapes because the files are read raw as often as
 * rendered, and `\<` stays legible where `&lt;` does not.
 */
/**
 * A field value, made safe to interpolate anywhere.
 *
 * The invariant is one sentence: **generated structure lives at the start of a
 * line, and a field value never contains the start of a line.** Escaping a
 * growing list of tokens was the first attempt and it lost, because Markdown's
 * block grammar is larger than the list: a note containing a bold line reading
 * "Superseded by E2" rendered byte-identical to the real retirement banner,
 * and the tool called the log clean. Collapsing the value to a single line
 * closes that whole class at once - a heading, a banner, a blockquote, a rule
 * and a list item all need a line to begin on, and there is none.
 *
 * What is left is inline grammar, which can make an entry's own text look odd
 * but cannot forge structure. Link syntax is escaped anyway, because a
 * statement closing the index's link and opening its own points a reader
 * somewhere the log did not choose.
 */
/**
 * Every character a renderer or a tokenizer may treat as ending a line.
 *
 * The first version of this collapse matched `\r?\n` and nothing else, so a
 * lone carriage return and the Unicode separators walked straight through and
 * forged a heading and a retirement banner. The check written to guard the
 * property fed only `\n` and agreed with the code, which is how both stayed
 * wrong: a check that shares the code's assumption checks nothing.
 */
const LINE_BREAK = /[ \t]*[\r\n\u000b\u000c\u0085\u2028\u2029]+[ \t]*/g;

export function mdInline(value: string): string {
  return value
    .replace(LINE_BREAK, " ")
    .replaceAll("<", "\\<")
    // `\<!--` still contains the marker as a substring, and the files are
    // read raw more often than rendered; break the comment opener itself.
    .replaceAll("<!--", "<\\!--")
    .replaceAll("[", "\\[")
    .replaceAll("]", "\\]")
    // Collapsing removes the line starts a value could create. This covers the
    // one it could still inherit: a template placing a value first on a line.
    .replace(/^([#>\-*+=])/, "\\$1");
}

/** Kept as a name for the places that must be one line. Same guarantee now. */
export const mdLine = mdInline;

/** A table cell: everything above, and `|` may not close it. */
export function mdCell(value: string): string {
  return mdInline(value).replaceAll("|", "\\|");
}

