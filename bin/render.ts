const SECTIONS: [string, keyof Entry][] = [
  ["Trigger", "trigger"],
  ["Decision", "decision"],
  ["Why", "why"],
  ["Implementation", "implementation"],
  ["Consequence", "consequence"],
  ["Falsifier", "falsifier"],
];

function label(entry: Loaded): string {
  // The E-number where one was ever issued; the stem - date plus slug, which
  // says what was decided - since E107 stopped minting them. Both resolve.
  return entry.alias ?? entry.stem ?? entry.id;
}

type Retirement = { by: string; extent: "whole" | "part"; detail: string | null };

/**
 * Who supersedes whom, and how far.
 *
 * The extent lives on the successor, so an entry's own banner used to say only
 * "Superseded by E28" while E28 was replacing one aspect of it. A reader of the
 * entry alone would retire rules that still hold, which is exactly what the
 * extent was introduced to prevent.
 */
function retirements(entries: Loaded[]): Map<string, Retirement[]> {
  const byName = new Map<string, Retirement[]>();
  for (const entry of entries) {
    for (const link of entry.supersedes) {
      const held = byName.get(link.id) ?? [];
      held.push({
        by: label(entry),
        extent: link.extent,
        detail: link.detail,
      });
      byName.set(link.id, held);
    }
  }
  return byName;
}

function retirementOf(
  entry: Loaded,
  map: Map<string, Retirement[]>,
): Retirement[] {
  return [
    ...(map.get(entry.id) ?? []),
    ...(entry.alias ? (map.get(entry.alias) ?? []) : []),
  ];
}

/**
 * Everything about a supersede link that renders without complaint but cannot
 * be true. The resolver used to swallow all of these, so a hand-edited or
 * imported log printed impossible banners with exit 0.
 */
/** A filename save would never mint. Refused rather than escaped. */
const SAFE_STEM = /^[a-z0-9][a-z0-9.-]*$/;

/**
 * The filename is the one thing in a rendered file that is not a field value,
 * and it was the one thing not escaped: it goes into the index link and into
 * the generated marker. save mints safe slugs, but render reads whatever json
 * is present, and an imported or hand-added file names itself.
 */
export function stemProblems(entries: Loaded[]): string[] {
  return entries
    .filter((entry) => !SAFE_STEM.test(entry.stem))
    .map(
      (entry) =>
        `${entry.stem}.json has a name that cannot appear in a link or a ` +
        `marker without changing what they mean. Rename it to lowercase ` +
        `letters, digits and hyphens.`,
    );
}

/**
 * Two entries that answer to one name.
 *
 * save claims its handle so that two writers cannot take the same one, but a
 * file arriving any other way - copied from another project, restored from a
 * backup, written by hand - brings whatever handle it had. Every log's first
 * entry is E1, so a copy between projects collides by default rather than by
 * accident. Nothing noticed: both entries rendered, and the fold report named
 * the pending one "E1" without being able to say which E1 it meant.
 *
 * An id counts as a name here too, because a reference is looked up by id or
 * by handle, so one entry's handle equal to another's id is the same ambiguity
 * wearing different clothes.
 *
 * Refused rather than repaired: which of the two keeps the handle is a
 * judgement about somebody else's entry, and renumbering is forbidden anyway.
 * The message says what to do, and a person decides.
 */
export function handleProblems(entries: Loaded[]): string[] {
  const seen = new Map<string, Loaded[]>();
  for (const entry of entries) {
    for (const name of new Set([entry.id, entry.alias].filter(Boolean))) {
      const held = seen.get(name as string) ?? [];
      held.push(entry);
      seen.set(name as string, held);
    }
  }

  const problems: string[] = [];
  for (const [name, held] of seen) {
    if (held.length < 2) continue;
    const where = held
      .map((entry) => `${entry.stem}.json (origin ${entry.origin ?? "unset"})`)
      .join(" and ");
    // Two files under one ID are the same entry twice; the alias advice fit
    // only the legacy-number collision and could not repair this one.
    problems.push(
      held[0].id === name
        ? `${where} both answer to ${name}. The same entry landed twice; ` +
          `remove one of the two files.`
        : `${where} both answer to ${name}. A reference to ${name} cannot ` +
          `mean one of them. An entry from another project keeps its id, ` +
          `its date and its origin; the number is the one thing it sets ` +
          `down, since no entry needs one here. Remove the "alias" from ` +
          `the arriving file - a number this log never issued would be a ` +
          `citation nothing ever made.`,
    );
  }
  return problems;
}

export function linkProblems(entries: Loaded[]): string[] {
  const names = new Set<string>();
  for (const entry of entries) {
    names.add(entry.id);
    if (entry.alias) names.add(entry.alias);
  }

  const problems: string[] = [];
  for (const entry of entries) {
    for (const link of entry.supersedes) {
      const who = label(entry);
      if (!names.has(link.id)) {
        problems.push(`${who} supersedes ${link.id}, which is not in the log`);
      }
      if (link.id === entry.id || link.id === entry.alias) {
        problems.push(`${who} supersedes itself`);
      }
      if (link.extent === "part" && !link.detail) {
        problems.push(
          `${who} supersedes ${link.id} in part without saying what was ` +
            `replaced, so the banner would name nothing`,
        );
      }
    }
  }

  // A ring of whole-extent links renders as a truth that cannot be: every
  // member's page says nothing of it still holds, and the fold would then
  // retire them all. Refused while whoever typed the closing link is still
  // there to hear it, like every other impossible link.
  const canonical = new Map<string, string>();
  for (const entry of entries) {
    canonical.set(entry.id, entry.id);
    if (entry.alias) canonical.set(entry.alias, entry.id);
  }
  const byId = new Map(entries.map((entry) => [entry.id, entry]));
  const wholly = (id: string): string[] =>
    (byId.get(id)?.supersedes ?? [])
      .filter((link) => link.extent === "whole")
      .map((link) => canonical.get(link.id))
      .filter((one): one is string => one !== undefined);
  const seen = new Map<string, "in" | "done">();
  const walk = (id: string, trail: string[]): void => {
    const state = seen.get(id);
    if (state === "done") return;
    if (state === "in") {
      const ring = trail.slice(trail.indexOf(id)).map((one) => label(byId.get(one)!));
      problems.push(
        `${ring.join(" retires ")} retires ${ring[0]} outright, a ring in ` +
          `which nothing still holds`,
      );
      return;
    }
    seen.set(id, "in");
    for (const next of wholly(id)) walk(next, [...trail, id]);
    seen.set(id, "done");
  };
  for (const entry of entries) walk(entry.id, []);

  return problems;
}

function retirementLine(one: Retirement): string {
  return one.extent === "whole"
    ? `**Superseded by ${mdLine(one.by)}.** Nothing of this entry still holds.`
    : `**Superseded in part by ${mdLine(one.by)}:** ${mdLine(one.detail ?? "")}` +
      `${/[.!?]$/.test((one.detail ?? "").trim()) ? "" : "."} ` +
      `Everything else in this entry still holds.`;
}

/** Chronological, and within a day by the numeric part of the alias. */
function orderKey(entry: Loaded): [string, number, string] {
  const digits = entry.alias?.slice(1) ?? "";
  return [entry.date, /^\d+$/.test(digits) ? Number(digits) : 0, entry.id];
}

export function load(dir: string): Loaded[] {
  // A root can be marked by DECISIONS.md alone, with decisions/ deleted or
  // never created. That is a log with no entries, which the caller handles -
  // the raw ENOENT here made the cleanup for exactly this case unreachable.
  if (!existsSync(dir)) return [];
  const entries = readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .map((name) => {
      const raw = readEntryFile(join(dir, name));
      if (raw === null || typeof raw !== "object" || Array.isArray(raw)) {
        throw new Error(
          `${name} is not a decision object. Fix or move it, then run again.`,
        );
      }
      // Normalise the shape at the read boundary: save always writes the full
      // default structure, but an imported, hand-added or merge-conflicted
      // entry may omit an optional array the schema does not require. These
      // are the only fields the renderer iterates unconditionally, so backfill
      // them here and downstream code deals only with content, never shape. A
      // present-but-wrong-type value is left as is, so validate still refuses
      // and names it rather than this masking it as empty. Required fields are
      // never backfilled: a genuine gap must stay visible as a gap.
      const entry = raw as unknown as Entry;
      return {
        ...entry,
        supersedes: entry.supersedes ?? [],
        rejected: entry.rejected ?? [],
        stem: basename(name, ".json"),
      };
    });
  return entries.sort((a, b) => {
    const [ad, an, ai] = orderKey(a);
    const [bd, bn, bi] = orderKey(b);
    return ad.localeCompare(bd) || an - bn || ai.localeCompare(bi);
  });
}

function renderEntry(
  entry: Loaded,
  retired: Retirement[],
  shown: Map<string, string>,
): string {
  const out: string[] = [
    `<!-- generated by bin/render.ts from ${mdInline(entry.stem)}.json - do not edit, ` +
      `edit the JSON -->`,
    "",
    `# ${mdLine(label(entry))} · ${mdLine(entry.statement)}`,
    "",
  ];

  out.push(
    `*${mdLine(entry.date)}` +
      `${entry.provenance ? ` · ${mdLine(entry.provenance)}` : ""}*`,
  );
  if (entry.note) out.push(`*(${mdInline(entry.note)})*`);
  for (const one of retired) out.push("", retirementLine(one));
  const gaps = missingFields(entry, LATEST);
  if (gaps.length) {
    out.push(
      "",
      `> **Incomplete.** Still missing: ${gaps.join(", ")}. ` +
        `Complete it with ` +
          `\`node <bosun>/dist/save.mjs --id ${mdLine(label(entry))} ...\`.`,
    );
  }
  out.push("");

  if (entry.quote) {
    // Every line of the quote stays inside the blockquote, so a quote can
    // never put text at the start of a line where it would read as structure.
    const quoted = mdInline(entry.quote.text)
      .split("\n")
      .map((line) => `> ${line}`)
      .join("\n");
    out.push(quoted, "");
  }

  for (const [title, key] of SECTIONS) {
    if (key === "why") {
      if (entry.why) out.push(`**Why** — ${mdInline(entry.why)}`, "");
      for (const rejected of entry.rejected) {
        out.push(
          `**Rejected: ${mdLine(rejected.option)}.** ` +
            mdInline(rejected.because),
          "",
        );
      }
      continue;
    }
    const value = entry[key];
    if (value) out.push(`**${title}** — ${mdInline(String(value))}`, "");
  }

  const meta = [
    `origin \`${mdLine(entry.origin)}\``,
    `by \`${mdLine(entry.author_role)}\``,
  ];
  if (entry.reason_type) meta.push(`reason \`${mdLine(entry.reason_type)}\``);
  for (const one of entry.supersedes) {
    // The stored link is the id; the shown link is the name a reader can
    // recognise, since E107 made stems what everything else displays.
    const named = shown.get(one.id) ?? one.id;
    meta.push(
      one.extent === "whole"
        ? `supersedes ${mdLine(named)}`
        : `supersedes ${mdLine(named)} in part (${mdLine(one.detail ?? "")})`,
    );
  }
  out.push("---", "", meta.join(" · "));

  return out.join("\n").replace(/\s+$/, "") + "\n";
}

function renderIndex(
  entries: Loaded[],
  own: boolean,
  map: Map<string, Retirement[]>,
): string {
  const out = [
    INDEX_MARKER,
    "",
    own ? PREAMBLE : GENERIC_PREAMBLE,
    "| | Decision | Date | Status |",
    "|---|---|---|---|",
  ];
  for (const entry of entries) {
    const gaps = missingFields(entry, LATEST);
    const retired = retirementOf(entry, map);
    const status = retired.length
      ? retired
          .map((one) =>
            one.extent === "whole"
              ? `superseded by ${mdCell(one.by)}`
              : `superseded **in part** by ${mdCell(one.by)}`,
          )
          .join(", ")
      : gaps.length
        ? `**incomplete**: ${gaps.join(", ")}`
        : "";
    const link = `decisions/${mdCell(entry.stem)}.md`;
    out.push(
      `| ${mdCell(label(entry))} | [${mdCell(entry.statement)}](${link}) ` +
        `| ${mdCell(entry.date)} | ${status} |`,
    );
  }
  if (own) out.push("", "Open questions live in [`OPEN.md`](OPEN.md).");
  return out.join("\n") + "\n";
}

export function main(passed: string[]): number {
  const { rest: argv, from } = takeLog(passed);
  const unknown = unknownFlag(argv, ["--check"]);
  if (unknown) {
    console.error(`refused: unknown flag ${unknown}`);
    return 1;
  }
  const check = argv.includes("--check");
  const root = logRoot(from);
  if (!root) {
    console.error(noLogRoot(from));
    return 1;
  }
  const dir = decisionsDir(root);
  let entries: Loaded[];
  try {
    entries = load(dir);
  } catch (error) {
    console.error("refused:", (error as Error).message);
    return 1;
  }
  if (entries.length === 0) {
    // An empty log is legitimate - a project that has decided nothing yet. What
    // is not legitimate is the index and the pages of a log that was emptied:
    // they outlived their source and kept pointing at files that are gone.
    const index = join(root, "DECISIONS.md");
    const left = [
      ...(existsSync(dir)
        ? readdirSync(dir)
            .filter((name) => name.endsWith(".md"))
            .map((name) => join(dir, name))
        : []),
      ...(existsSync(index) ? [index] : []),
    ].filter((path) =>
      readFileSync(path, "utf8").startsWith("<!-- generated by bin/render.ts"),
    );

    if (left.length === 0) {
      console.log(`no entries in ${dir}, nothing to render`);
      return 0;
    }
    for (const path of left) {
      console.log(
        check ? "  no entry behind it any more:" : "  removed:",
        path.slice(root.length + 1),
      );
      if (!check) rmSync(path);
    }
    console.log(
      check
        ? `${left.length} generated file(s) outlived the log`
        : `${left.length} generated file(s) removed, the log is empty`,
    );
    return check ? 1 : 0;
  }

  // A DECISIONS.md that bosun did not write belongs to somebody else. It used
  // to be replaced silently on the first save.
  const index = join(root, "DECISIONS.md");
  const held = existsSync(index) ? readFileSync(index, "utf8") : null;
  // An empty DECISIONS.md is a placeholder somebody created to mark the
  // project, not somebody's writing. Refusing it left such a project unable to
  // ever get an index.
  const foreign =
    held !== null && held.trim() !== "" && !held.startsWith(INDEX_MARKER);
  // Whose history this is follows from what the index already says, not from
  // where the scripts happen to live: two checkouts used to rewrite each
  // other's preamble.
  const own =
    root === SCRIPT_ROOT ||
    (held?.includes("E1 to E12 come from a single conversation") ?? false);
  if (foreign) {
    console.error(
      `refusing to overwrite ${index}: it was not generated by bosun. ` +
        `Move it aside, then run again.`,
    );
  }

  // An older entry is pointed at the tool that reads it, never judged by the
  // newest schema: measured against v7, a valid v6 field was refused as "not
  // allowed" - advice to hand-delete data the migration converts.
  const dated = entries
    .filter((entry) => ((entry.schema as number) ?? 1) < LATEST)
    .map((entry) => `${entry.stem}.json is schema v${(entry.schema as number) ?? 1}`);
  if (dated.length) {
    for (const line of dated) console.error(`  ${line}`);
    console.error(
      `refused: ${dated.length} entr${dated.length === 1 ? "y is" : "ies are"} ` +
        `older than this checkout writes. Run upgrade.mjs once, then render.`,
    );
    return 1;
  }

  // render was the only log tool that never validated. upgrade and save both
  // did, and both produced a usable message for the same bad file.
  const invalid = entries.flatMap(({ stem, ...entry }) =>
    validate(entry, LATEST)
      .filter((problem) => problem.kind === "invalid")
      .map((problem) => `${stem}.json: ${problem.path} ${problem.message}`),
  );
  // Type errors are settled first, alone. linkProblems and renderEntry iterate
  // supersedes and rejected, so a value that validate flags as the wrong type
  // (an object where an array belongs) would crash them before its own refusal
  // was printed. Refusing here means the structural checks only ever run on
  // entries whose shape validate has already accepted.
  if (invalid.length) {
    for (const problem of invalid) console.error("  refused:", problem);
    console.error(
      `refusing to write: ${invalid.length} problem(s) above. ` +
        `Nothing was generated.`,
    );
    return 1;
  }
  const broken = [
    ...handleProblems(entries),
    ...linkProblems(entries),
    ...stemProblems(entries),
  ];
  for (const problem of broken) console.error("  refused:", problem);
  // Nothing is written while anything is refused. Reporting a problem and
  // writing the file anyway leaves the forgery on disk for everyone who does
  // not read the exit code, which is most people running a render by hand.
  // upgrade.ts already worked this way; render did not.
  if (broken.length) {
    console.error(
      `refusing to write: ${broken.length} problem(s) above. ` +
        `Nothing was generated.`,
    );
    return 1;
  }

  // A generated file whose source is gone is derived rubbish, and until now it
  // survived every render: the index was corrected, the orphaned page stayed,
  // and --check reported clean because it only ever compared files that ought
  // to exist. Reported here, and removed on the write path - E46 says a derived
  // artefact may be deleted and rebuilt; it is never the source.
  const generated = existsSync(dir)
    ? readdirSync(dir)
        .filter((name) => name.endsWith(".md"))
        .map((name) => join(dir, name))
        .filter((path) =>
          readFileSync(path, "utf8").startsWith("<!-- generated by bin/render.ts"),
        )
    : [];

  const map = retirements(entries);
  // Ids resolve to the names readers recognise, for every page's footer.
  const shown = new Map<string, string>();
  for (const entry of entries) {
    shown.set(entry.id, label(entry));
    if (entry.alias) shown.set(entry.alias, label(entry));
  }
  const wanted = new Map<string, string>(
    foreign ? [] : [[index, renderIndex(entries, own, map)]],
  );
  for (const entry of entries) {
    wanted.set(
      join(dir, `${entry.stem}.md`),
      renderEntry(entry, retirementOf(entry, map), shown),
    );
  }

  const stale = generated.filter((path) => !wanted.has(path));

  const drift: string[] = [];
  for (const path of stale) {
    drift.push(path.slice(root.length + 1));
    if (!check) rmSync(path);
  }
  let kept = 0;
  for (const [path, text] of wanted) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === text) continue;
    // The same rule the index gets: a file bosun did not write belongs to
    // somebody else. A hand-written decisions/notes.md used to be replaced
    // silently the moment a notes.json appeared beside it.
    if (current !== null && current.trim() !== "" &&
        !current.startsWith(GENERATED_PREFIX)) {
      kept += 1;
      console.error(
        `refusing to overwrite ${path}: it was not generated by bosun. ` +
          `Move it aside, then run again.`,
      );
      continue;
    }
    drift.push(path.slice(root.length + 1));
    if (!check) writeFileSync(path, text, "utf8");
  }

  if (check) {
    for (const path of drift) console.log("out of date:", path);
    for (const path of stale) {
      console.log("  no entry behind it any more:", path.slice(root.length + 1));
    }
    console.log(
      `${entries.length} entries, ${drift.length} out of date` +
        (foreign ? ", index refused" : "") +
        (kept ? `, ${kept} file(s) refused` : ""),
    );
    return drift.length || foreign || broken.length || kept ? 1 : 0;
  }

  // Retiring a rule is loud on the save path. A hand-added or imported entry
  // never touches save, so the loud moment has to exist here too - this is
  // what CI runs, and it is where a pull request arrives.
  // The retiree is shown by its label, not by whatever string the link holds:
  // links store full ids since E107, and a raw id names nothing to a reader.
  const canonical = new Map<string, Loaded>();
  for (const entry of entries) {
    canonical.set(entry.id, entry);
    if (entry.alias) canonical.set(entry.alias, entry);
  }
  const retired = entries.flatMap((entry) =>
    entry.supersedes
      .filter((link) => link.extent === "whole")
      .map((link) => {
        const target = canonical.get(link.id);
        return `${target ? label(target) : link.id} retired outright by ${label(entry)}`;
      }),
  );
  if (retired.length) {
    // Standing state of the log, not the news of this run: printed the same
    // on every render, it read as if the latest save had just done the
    // retiring, and an adopter re-read it three times looking for what broke.
    console.log(
      `  ${retired.length} whole-extent link(s) stand in this log:`,
    );
    for (const line of retired) console.log(`    ${line}`);
  }
  if (stale.length) {
    console.log(`  ${stale.length} generated file(s) removed, no entry behind them`);
  }
  console.log(
    `${entries.length} entries rendered, ${drift.length} file(s) changed`,
  );
  // The entries are written either way; a non-zero status says something is
  // not - a refused index, a refused file, a bad link - which is a state the
  // caller has to know about.
  return foreign || broken.length || kept ? 1 : 0;
}

// Only when run directly. Importing this file must not execute it,
// otherwise no test and no other script can load it.
// realpathSync on both sides: Node canonicalises import.meta.url through
// symlinks but leaves process.argv[1] as typed, so reaching a script through
// a symlinked path (/tmp on macOS, a dotfile manager, a network home) made
// every one of these silently do nothing and exit 0. A save that reports
// success and records nothing is worse than one that crashes.
if (isDirectRun(import.meta.url)) {
  // A bad file is named and refused, never a crash: the last net for
  // anything a shape check below main did not already turn into a clean
  // refusal. save.ts wraps its main the same way.
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    console.error("refused:", (error as Error).message);
    process.exitCode = 1;
  }
}
